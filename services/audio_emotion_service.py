# Default Gemini models verified for multimodal reasoning and structured outputs
# gemini-3.5-flash-lite and gemini-3.5-flash are verified models with active Free Tier quota
DEFAULT_EMOTION_MODEL = "gemini-3.5-flash-lite"
RESILIENT_FALLBACK_MODELS = ["gemini-3.5-flash", "gemini-3.1-flash-lite", "gemini-3.8-flash"]


class AudioEmotionServiceError(Exception):
    """Raised when an error occurs during acoustic emotion analysis."""
    pass


class GeminiAcousticResponse(BaseModel):
    """Structured acoustic analysis schema generated by Gemini without free-form dictionaries."""

    detected_emotion: str = Field(
        description="Core emotion category: 'Calm / Neutral', 'Happy / Excited', 'Sad', 'Worried / Anxious', 'Frustrated / Angry', 'Surprised', or 'Neutral / Uncertain'."
    )
    emotion_confidence: str = Field(
        description="Confidence level in the acoustic emotion detection: 'low', 'medium', or 'high'."
    )
    emotional_intensity: str = Field(
        description="Intensity of the emotion: 'subtle', 'moderate', 'high', or 'intense'."
    )
    vocal_energy: str = Field(
        default="moderate",
        description="Perceived vocal energy/loudness: 'low', 'moderate', or 'high'."
    )
    speaking_pace: str = Field(
        default="moderate",
        description="Estimated speaking pace: 'slow', 'moderate', or 'fast'."
    )
    pitch_variation: str = Field(
        default="subtle variation",
        description="Pitch dynamics: 'monotone', 'subtle variation', or 'wide / animated variation'."
    )
    voice_tension_or_softness: str = Field(
        default="neutral",
        description="Vocal tension: 'relaxed / soft', 'neutral', 'strained / tense', or 'breathy'."
    )
    speaking_style: str = Field(
        description="Perceived speaking style (e.g., 'Conversational & Upbeat', 'Subdued & Monotone', 'Urgent & Tense', 'Calm & Deliberate')."
    )
    supporting_observations: List[str] = Field(
        default_factory=list,
        description="Acoustic and vocal observations supporting the detection (e.g., 'Elevated pitch on final syllables', 'Rapid tempo with minimal pauses', 'High vocal energy')."
    )
    is_uncertain: bool = Field(
        default=False,
        description="Flag indicating if the acoustic signal or emotional context is ambiguous."
    )
    suggested_tts_speed: float = Field(
        default=1.0,
        description="Recommended speech speed for TTS delivery based on detected pace and energy (0.85 to 1.2)."
    )
    suggested_delivery_style: str = Field(
        description="Instructional delivery guidance for synthesized voice (e.g., 'Warm and energetic English delivery')."
    )


class AudioEmotionAnalysis(GeminiAcousticResponse):
    """Complete acoustic analysis result including local digital signal processing (DSP) metrics."""

    acoustic_metrics: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Concrete digital signal processing (DSP) metrics extracted from audio if WAV format."
    )


def extract_local_acoustic_features(audio_path: Union[str, Path]) -> Dict[str, Any]:
    """Extracts digital signal processing (DSP) acoustic features from a local audio file.

    For PCM WAV files, computes energy dynamics, zero-crossing rate, dynamic range,
    and pause/silence ratio. For compressed audio formats (M4A, MP3), returns file-level
    metadata and signal parameters.
    """
    path_obj = Path(audio_path).resolve()
    if not path_obj.is_file():
        raise AudioEmotionServiceError(f"Audio file not found: {path_obj}")

    file_size_bytes = path_obj.stat().st_size
    file_ext = path_obj.suffix.lower()

    metrics: Dict[str, Any] = {
        "format": file_ext.replace(".", "").upper(),
        "file_size_kb": round(file_size_bytes / 1024, 1),
    }

    if file_ext == ".wav":
        try:
            with wave.open(str(path_obj), "rb") as wav_file:
                channels = wav_file.getnchannels()
                sample_width = wav_file.getsampwidth()
                framerate = wav_file.getframerate()
                num_frames = wav_file.getnframes()

                raw_bytes = wav_file.readframes(num_frames)
                actual_frames = len(raw_bytes) // (channels * sample_width) if (channels * sample_width) > 0 else 0
                duration_sec = round(actual_frames / framerate, 2) if framerate > 0 else 0.0

                metrics.update({
                    "channels": "Mono" if channels == 1 else f"Stereo ({channels})",
                    "sample_rate_hz": framerate,
                    "duration_seconds": duration_sec,
                })

                if sample_width == 2 and len(raw_bytes) > 0:
                    samples = np.frombuffer(raw_bytes, dtype=np.int16).astype(np.float32)
                    if len(samples) > 0:
                        # RMS Energy (loudness/power)
                        rms = np.sqrt(np.mean(samples ** 2))
                        peak = np.max(np.abs(samples))
                        peak_to_rms = round(float(peak / (rms + 1e-6)), 2)

                        # Zero-Crossing Rate (ZCR) - correlates with voice brightness & fricatives
                        zcr = np.mean(np.diff(np.sign(samples)) != 0)

                        # Frame-level energy distribution for pause/silence ratio
                        frame_size = int(framerate * 0.03)  # 30ms window
                        if frame_size > 0 and len(samples) >= frame_size:
                            num_windows = len(samples) // frame_size
                            trimmed = samples[: num_windows * frame_size].reshape(num_windows, frame_size)
                            window_rms = np.sqrt(np.mean(trimmed ** 2, axis=1))
                            silence_threshold = 0.15 * np.mean(window_rms)
                            silence_ratio = round(float(np.mean(window_rms < silence_threshold)), 2)
                        else:
                            silence_ratio = 0.0

                        metrics.update({
                            "rms_energy": round(float(rms), 1),
                            "dynamic_range_ratio": peak_to_rms,
                            "zero_crossing_rate": round(float(zcr), 4),
                            "pause_ratio": silence_ratio,
                            "energy_level": "High" if rms > 4500 else ("Moderate" if rms > 2000 else "Subdued"),
                        })
        except Exception as e:
            metrics["dsp_note"] = f"WAV DSP extraction skipped: {e}"
    else:
        metrics.update({
            "dsp_note": "Acoustic characteristics analyzed via native multimodal speech perception.",
        })

    return metrics


def get_audio_mime_type(audio_path: Path) -> str:
    """Returns the MIME type string corresponding to the audio file extension."""
    ext = audio_path.suffix.lower()
    mime_map = {
        ".wav": "audio/wav",
        ".m4a": "audio/m4a",
        ".mp3": "audio/mp3",
        ".ogg": "audio/ogg",
        ".flac": "audio/flac",
        ".aac": "audio/aac",
    }
    return mime_map.get(ext, mimetypes.guess_type(str(audio_path))[0] or "audio/wav")


# Expert prompt instructing Gemini to analyze vocal acoustic expression
ACOUSTIC_EMOTION_SYSTEM_PROMPT = """
You are an expert speech acoustic and phonetics analyst specializing in Indian spoken languages (including Malayalam).
Your task is to analyze the speaker's vocal recording directly to evaluate their emotional expression based purely on physical acoustic characteristics:
- Pitch dynamics and contour (rising, falling, flat, animated).
- Speaking rate, tempo, and cadence (steady, measured, rushed, sluggish).
- Vocal energy, loudness, and acoustic projection.
- Pauses, hesitations, and prosodic rhythm.
- Vocal tension (relaxed/soft, neutral, strained/tense, breathy).
- Overall vocal demeanor.

CRITICAL ACOUSTIC RULES:
1. PURE ACOUSTIC EVALUATION (NO TRANSCRIPT OR SEMANTIC BIAS):
   - Base your emotion assessment STRICTLY on HOW the words are physically spoken.
   - DO NOT infer emotion from assumed words, transcript semantics, or topic.
   - A speaker discussing serious, difficult, sad, or worrying situations in a steady, calm, or matter-of-fact tone MUST be classified as 'Calm / Neutral'.

2. CALM, CASUAL, OR MEASURED SPEECH IS 'CALM / NEUTRAL':
   - Everyday conversational speech, relaxed talking, casual remarks, or matter-of-fact speaking MUST be classified as 'Calm / Neutral'.
   - Soft vocal projection, lower volume, slower tempo, or natural conversational pauses are NATURAL traits of calm, relaxed delivery. NEVER classify these as 'Sad'.
   - Do NOT equate quietness, relaxed vocal cords, or low dynamic range with sadness.

3. STRICT CRITERIA FOR 'SAD':
   - ONLY classify as 'Sad' when there is clear, unmistakable acoustic evidence of genuine grief, sorrow, or crying (e.g., choked vocal breaks, audible sobbing, weeping breath catches, or audibly trembling despondency).
   - If the speaker merely sounds calm, quiet, tired, serious, or neutral without audible crying or distress, classify as 'Calm / Neutral' (or 'Neutral / Uncertain').
   - Low energy, slow speech, quiet volume, or pauses ALONE NEVER justify a 'Sad' classification.

4. EMOTION CATEGORIES:
   - 'Calm / Neutral': Steady, relaxed rhythm, measured tempo, natural conversational pitch with no audible distress or tension.
   - 'Happy / Excited': Upbeat tempo, animated pitch modulation, bright vocal energy, lively resonance, and forward momentum.
   - 'Worried / Anxious': Audible vocal tremors, rapid pitch fluctuation, breathy hesitation, or audible distress in the voice.
   - 'Frustrated / Angry': Elevated vocal projection, sharp articulation, harsh vocal effort, or strained vocal cords.
   - 'Sad': Audible weeping, choked vocal cords, audibly trembling sorrow, or heavy grief-stricken cadence (requires unambiguous acoustic crying/distress).
   - 'Surprised': Abrupt pitch elevation with rapid dynamic inflection shifts.
   - 'Neutral / Uncertain': Subtle, ambiguous, or balanced indicators with no clear extreme emotion.

5. GENUINE NEUTRAL / UNCERTAIN DEFAULT:
   - If vocal indicators are subtle, ambiguous, or balanced, select 'Calm / Neutral' or 'Neutral / Uncertain', set is_uncertain=True, and rate emotion_confidence as 'low' or 'medium'.
   - Do NOT force calm recordings into negative emotion categories.
   - Low acoustic evidence MUST produce 'Calm / Neutral' or 'Neutral / Uncertain', never 'Sad'.

6. PSYCHOLOGICAL HUMILITY & CULTURAL OBJECTIVITY:
   - Never present acoustic detection as proven psychological diagnosis or internal mind-reading. Frame findings strictly as acoustic observations of vocal delivery.
   - Natural dynamic range in conversational Malayalam should not be falsely classified as anger, distress, or sadness unless acoustic tension and hostility or weeping are evident.

7. ATTRIBUTE BREAKDOWN:
   - Set emotional_intensity as 'subtle', 'moderate', 'high', or 'intense'.
   - Set vocal_energy as 'low', 'moderate', or 'high'.
   - Set speaking_pace as 'slow', 'moderate', or 'fast'.
   - Set pitch_variation as 'monotone', 'subtle variation', or 'wide / animated variation'.
   - Set voice_tension_or_softness as 'relaxed / soft', 'neutral', 'strained / tense', or 'breathy'.

8. SUPPORTING ACOUSTIC EVIDENCE:
   - Provide concrete, evidence-based supporting vocal observations (e.g., 'Steady pitch contour with relaxed vocal tract and measured pauses').

9. Provide a recommended TTS speed (between 0.88 and 1.15) reflecting the speaker's tempo (default 1.0 if calm or uncertain).
10. Return strictly valid JSON matching the requested schema.
"""


def analyze_audio_emotion(
    audio_path: Union[str, Path],
    model_name: str = DEFAULT_EMOTION_MODEL,
) -> AudioEmotionAnalysis:
    """Performs pure acoustic emotion analysis on an audio file using Gemini multimodal perception.
    
    Analyses the vocal signal directly without receiving or relying on the transcript, ensuring
    semantic vocabulary does not bias acoustic emotion recognition. Tries gemini-3.8-flash first
    and automatically falls back to gemini-3.5-flash if quota is exhausted.

    Args:
        audio_path: Path to the audio file on disk.
        model_name: Gemini model name (default 'gemini-3.8-flash').

    Returns:
        AudioEmotionAnalysis containing emotion, intensity, confidence, style,
        supporting observations, and recommended delivery speed.
    """
    path_obj = Path(audio_path).resolve()
    if not path_obj.is_file():
        raise AudioEmotionServiceError(f"Audio file not found: {path_obj}")

    load_dotenv()
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key or not api_key.strip():
        raise AudioEmotionServiceError(
            "GEMINI_API_KEY is not set in environment or .env file."
        )

    # 1. Extract local DSP acoustic metrics
    dsp_metrics = extract_local_acoustic_features(path_obj)

    # 2. Read audio binary data
    with open(path_obj, "rb") as f:
        audio_bytes = f.read()

    mime_type = get_audio_mime_type(path_obj)

    # 3. Import SDK modules dynamically
    try:
        from google import genai
        from google.genai import types
        from google.genai.errors import APIError
    except ImportError as imp_err:
        raise AudioEmotionServiceError(f"google-genai SDK not available: {imp_err}")

    try:
        client = genai.Client(
            api_key=api_key.strip(),
            http_options=types.HttpOptions(
                timeout=25000,
                retry_options=types.HttpRetryOptions(attempts=2),
            ),
        )
    except Exception as client_err:
        raise AudioEmotionServiceError(f"Failed to initialize Gemini Client: {client_err}")

    # 4. Prepare multimodal contents (PURE AUDIO, NO TRANSCRIPT)
    audio_part = types.Part.from_bytes(data=audio_bytes, mime_type=mime_type)

    user_prompt_text = (
        "Listen strictly to the physical vocal acoustics of this recording. "
        "Evaluate pitch contour, cadence, vocal volume projection, and vocal tension. "
        "DO NOT infer emotion from words or topics. "
        "If the speaker sounds calm, measured, relaxed, casual, quiet, or matter-of-fact, classify as 'Calm / Neutral'. "
        "Only classify as 'Sad' if there is genuine audible acoustic grief, sobbing, or weeping in the voice."
    )

    config = types.GenerateContentConfig(
        system_instruction=ACOUSTIC_EMOTION_SYSTEM_PROMPT,
        response_mime_type="application/json",
        response_schema=GeminiAcousticResponse,
    )

    models_to_try = [model_name]
    for fb in RESILIENT_FALLBACK_MODELS:
        if fb not in models_to_try:
            models_to_try.append(fb)

    last_error: Optional[Exception] = None
    for current_model in models_to_try:
        logger.info(f"Analyzing vocal acoustics using Gemini model '{current_model}'...")
        try:
            response = client.models.generate_content(
                model=current_model,
                contents=[audio_part, user_prompt_text],
                config=config,
            )

            if not response or not response.text:
                raise AudioEmotionServiceError(f"Gemini model '{current_model}' returned an empty response.")

            parsed_json = json.loads(response.text)
            gemini_acoustic = GeminiAcousticResponse.model_validate(parsed_json)
            analysis = AudioEmotionAnalysis(**gemini_acoustic.model_dump())
            # Attach concrete DSP metrics
            analysis.acoustic_metrics = dsp_metrics

            # Acoustic Safeguard: Prevent calm/neutral delivery from being misclassified as Sad
            detected_lower = analysis.detected_emotion.lower()
            tension_lower = (analysis.voice_tension_or_softness or "").lower()
            obs_text = " ".join(analysis.supporting_observations).lower()

            is_sad = any(w in detected_lower for w in ["sad", "subdued", "somber", "grief"])
            has_crying_distress = any(w in obs_text for w in ["cry", "weep", "sob", "chok", "distress", "tear", "tremor"])

            if is_sad:
                if tension_lower in ["relaxed / soft", "neutral", "relaxed", "soft"] and not has_crying_distress:
                    logger.info(
                        f"Acoustic safeguard applied: Overriding '{analysis.detected_emotion}' with 'Calm / Neutral' "
                        f"(vocal tension is '{analysis.voice_tension_or_softness}', no audible weeping/distress observed)."
                    )
                    analysis.detected_emotion = "Calm / Neutral"
                    analysis.is_uncertain = True
                elif analysis.emotion_confidence == "low":
                    logger.info(
                        f"Acoustic safeguard applied: Overriding '{analysis.detected_emotion}' with 'Neutral / Uncertain' "
                        f"(insufficient confidence on acoustic sadness)."
                    )
                    analysis.detected_emotion = "Neutral / Uncertain"
                    analysis.is_uncertain = True

            logger.info(
                f"Acoustic analysis succeeded with model '{current_model}': "
                f"Vibe='{analysis.detected_emotion}', Conf='{analysis.emotion_confidence}'."
            )
            return analysis

        except Exception as err:
            last_error = err
            logger.warning(
                f"Acoustic analysis attempt failed on model '{current_model}': {type(err).__name__} - {err}"
            )
            if current_model != models_to_try[-1]:
                logger.info(f"Attempting fallback model '{models_to_try[-1]}' for acoustic emotion...")
                continue
            if isinstance(err, APIError):
                code_info = f" (Status {err.code})" if hasattr(err, "code") else ""
                raise AudioEmotionServiceError(f"Gemini API Error{code_info}: {err.message}") from err
            if isinstance(err, AudioEmotionServiceError):
                raise
            raise AudioEmotionServiceError(f"Acoustic emotion analysis failed: {err}") from err

    if last_error:
        raise AudioEmotionServiceError(f"Acoustic emotion analysis failed: {last_error}") from last_error

